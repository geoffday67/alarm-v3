#!/usr/bin/env python3
"""Generates an Adafruit GFX bitmap font header from a TrueType font.

Renders each character monochrome (no antialiasing) with Pillow/FreeType and
packs it in the format Adafruit's fontconvert produces: per-glyph bitmaps,
row-major, MSB first, rows not byte-aligned, each glyph starting on a byte.

With --fit-width, picks the largest pixel size at which --fit-text's ink
width is no more than that many pixels, instead of using --size.

With --vcenter, moves those characters up or down (yOffset only, the bitmap
is unchanged) so their ink is centred vertically on the ink of the
--vcenter-on character; e.g. a colon centred on the digits.

Example (the clock digits):
  python3 make_gfx_font.py --ttf LiberationSans-Bold.ttf --name ClockDigits \\
      --chars 0123456789: --fit-text 14:44 --fit-width 237 \\
      --vcenter : --vcenter-on 0 --out ClockDigits.h
"""
import argparse

from PIL import Image, ImageDraw, ImageFont


def render(font, ch):
    """Returns (rows of 0/1, xOffset, yOffset, xAdvance) for one character."""
    size = font.size * 3
    origin = (size // 3, size * 2 // 3)  # baseline point, room on all sides
    img = Image.new("1", (size, size), 0)
    draw = ImageDraw.Draw(img)
    draw.fontmode = "1"  # FreeType monochrome rendering, no antialiasing
    draw.text(origin, ch, font=font, fill=1, anchor="ls")
    advance = round(font.getlength(ch))
    box = img.getbbox()
    if box is None:  # blank glyph (space)
        return [], 0, 0, advance
    x0, y0, x1, y1 = box
    rows = [[img.getpixel((x, y)) and 1 or 0 for x in range(x0, x1)] for y in range(y0, y1)]
    return rows, x0 - origin[0], y0 - origin[1], advance


def ink_width(font, text):
    img = Image.new("1", (font.size * (len(text) + 2), font.size * 2), 0)
    draw = ImageDraw.Draw(img)
    draw.fontmode = "1"
    draw.text((font.size, font.size * 3 // 2), text, font=font, fill=1, anchor="ls")
    x0, _, x1, _ = img.getbbox()
    return x1 - x0


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--ttf", required=True)
    p.add_argument("--name", required=True)
    p.add_argument("--chars", required=True, help="characters to include (contiguous range is filled)")
    p.add_argument("--size", type=int, help="pixel size (em)")
    p.add_argument("--fit-text")
    p.add_argument("--fit-width", type=int)
    p.add_argument("--vcenter", default="", help="characters to centre vertically")
    p.add_argument("--vcenter-on", help="character whose ink they're centred on")
    p.add_argument("--out", required=True)
    a = p.parse_args()

    if a.fit_width:
        size = 8
        while ink_width(ImageFont.truetype(a.ttf, size + 1), a.fit_text) <= a.fit_width:
            size += 1
    else:
        size = a.size
    font = ImageFont.truetype(a.ttf, size)

    first, last = ord(min(a.chars)), ord(max(a.chars))
    bitmap = bytearray()
    glyphs = []
    for code in range(first, last + 1):
        ch = chr(code)
        rows, xo, yo, adv = render(font, ch) if ch in a.chars else ([], 0, 0, 0)
        offset = len(bitmap)
        bits = [b for row in rows for b in row]
        for i in range(0, len(bits), 8):
            chunk = bits[i:i + 8] + [0] * (8 - len(bits[i:i + 8]))
            bitmap.append(sum(b << (7 - j) for j, b in enumerate(chunk)))
        w = len(rows[0]) if rows else 0
        glyphs.append((offset, w, len(rows), adv, xo, yo, ch))

    if a.vcenter:
        ref = next(g for g in glyphs if g[6] == a.vcenter_on)
        ref_centre2 = 2 * ref[5] + ref[2]  # twice the centre, to stay in integers
        for i, g in enumerate(glyphs):
            if g[6] in a.vcenter:
                yo = (ref_centre2 - g[2]) // 2
                glyphs[i] = g[:5] + (yo,) + g[6:]

    ascent, descent = font.getmetrics()
    with open(a.out, "w") as f:
        f.write("#pragma once\n#include <Adafruit_GFX.h>\n\n")
        f.write(f"// Generated by tools/make_gfx_font.py from {a.ttf.split('/')[-1]} at {size} px\n")
        f.write(f"// (em), characters {a.chars!r} only")
        if a.fit_width:
            f.write(f": the largest size at which {a.fit_text!r} is at most\n// {a.fit_width} px wide (ink)")
        if a.vcenter:
            f.write(f", with {a.vcenter!r} moved to centre vertically on {a.vcenter_on!r}")
        f.write(".\n\n")
        f.write(f"const uint8_t {a.name}Bitmaps[] PROGMEM = {{\n")
        for i in range(0, len(bitmap), 16):
            f.write("  " + ", ".join(f"0x{b:02X}" for b in bitmap[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write(f"const GFXglyph {a.name}Glyphs[] PROGMEM = {{\n")
        for off, w, h, adv, xo, yo, ch in glyphs:
            f.write(f"  {{{off:6d}, {w:3d}, {h:3d}, {adv:3d}, {xo:4d}, {yo:4d}}},  // 0x{ord(ch):02X} '{ch}'\n")
        f.write("};\n\n")
        f.write(f"const GFXfont {a.name} PROGMEM = {{\n  (uint8_t *){a.name}Bitmaps,\n"
                f"  (GFXglyph *){a.name}Glyphs,\n  0x{first:02X}, 0x{last:02X}, {ascent + descent}\n}};\n")
    print(f"size {size} px, '{a.fit_text}' ink width {ink_width(font, a.fit_text) if a.fit_text else '-'}, "
          f"{len(bitmap)} bitmap bytes")
    for off, w, h, adv, xo, yo, ch in glyphs:
        print(f"  {ch!r}: {w}x{h} adv {adv} off {xo},{yo}")


if __name__ == "__main__":
    main()
